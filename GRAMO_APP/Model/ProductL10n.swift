extension FoodCandidate {
    /// Recognition labels have an English source; manual names remain exactly as entered.
    func displayName(in language: AppLanguage) -> String {
        guard language == .en else { return name }
        guard modelVersion != "manual-v1" else { return name }
        let translated = L10n.text(name, language)
        if translated != name { return translated }
        return classID != nil && !rawLabel.isEmpty ? rawLabel : name
    }
