        (#"^约 ([\d.]+) (g|kcal)$"#, "About $1 $2"),
        (#"^目标进度 (.+)$"#, "Goal progress $1"),
        (#"^(\d+) 口$"#, "$1 bites"),
        (#"^(\d+) 口待确认$"#, "$1 bites to confirm"),
        (#"^队列：(\d+)$"#, "Queued: $1")
    ].map { (try! NSRegularExpression(pattern: $0.0), $0.1) }

    static func productPattern(_ source: String) -> String? {
        if source == "1 口" { return "1 bite" }
        if source == "1 口待完善" { return "1 bite needs details" }
        if source == "1 口已记录" { return "1 bite recorded" }
        if source.hasPrefix("我的餐勺，") { return "My spoon, " + text(String(source.dropFirst("我的餐勺，".count)), .en) }
        let range = NSRange(source.startIndex..., in: source)
        for (regex, template) in productPatterns where regex.firstMatch(in: source, range: range) != nil {
            return regex.stringByReplacingMatches(in: source, range: range, withTemplate: template)
        }
        // Separately translate composed UI labels, leaving user-entered names intact.
        if source.contains(" · ") {
            return source.components(separatedBy: " · ").map { text($0, .en) }.joined(separator: " · ")
        }
        for (prefix, translated) in [("餐勺画面 · ", "Spoon camera · "), ("短按前附近画面 · ", "Before press · "), ("短按后附近画面 · ", "After press · ")] {
            if source.hasPrefix(prefix) { return translated + source.dropFirst(prefix.count) }
        }
        return nil
    }
